import { afterEach, describe, expect, it, vi } from 'vitest'
import { chatHarness } from '../helpers/chat-harness'
const id = '11111111-1111-4111-8111-111111111111'
const memory = { enabled: true, pending_jobs: 0, failed_jobs: 0, observations: [{ id, category: 'preference', quote: 'Prefiero conversar despacio', status: 'confirmed', time_scope: 'current', source_created_at: '2026-10-01T12:00:00Z', updated_at: '2026-10-01T12:00:00Z', source_message_id: id, session_id: id, supersedes_id: null, disputed: false }] }
afterEach(() => vi.unstubAllEnvs())
describe('chat admission and isolated profile context', () => {
  it('with flag off never queries profile RPC or schedules its dispatch', async () => {
    vi.stubEnv('FEATURE_PROGRESSIVE_PROFILE', 'off')
    const harness = await chatHarness()
    expect((await harness.post()).status).toBe(200)
    expect(harness.authClient.rpc.mock.calls.flat()).not.toContain('get_profile_memory')
    expect(harness.state.profileAfter).toHaveLength(0)
  })
  it('schedules only after durable admission, without waiting for extraction, including replay', async () => {
    vi.stubEnv('FEATURE_PROGRESSIVE_PROFILE', 'on')
    const harness = await chatHarness()
    const response = await harness.post()
    await response.text()
    expect(response.status).toBe(200)
    expect(harness.state.profileAfter).toHaveLength(1)
    expect(harness.enqueueProfileExtraction).not.toHaveBeenCalled()
    await harness.state.profileAfter[0]()
    expect(harness.enqueueProfileExtraction).toHaveBeenCalledWith('user-1', 1)
    expect((await harness.post()).status).toBe(200)
    expect(harness.state.profileAfter).toHaveLength(2)
  })
  it('never schedules extraction for unauthorized or conflicting admission', async () => {
    vi.stubEnv('FEATURE_PROGRESSIVE_PROFILE', 'on')
    const harness = await chatHarness()
    harness.state.user = null
    expect((await harness.post()).status).toBe(401)
    harness.state.user = { id: 'user-1' }
    harness.state.turns.set('turn-1', { text: 'different', status: 'generating' })
    expect((await harness.post()).status).toBe(422)
    expect(harness.state.profileAfter).toHaveLength(0)
  })
  it('uses only the authenticated owner projection, refreshes it each turn and preserves chat on failure', async () => {
    vi.stubEnv('FEATURE_PROGRESSIVE_PROFILE', 'on')
    const harness = await chatHarness()
    harness.authClient.rpc.mockImplementation(async (name: string) => name === 'get_profile_memory' ? { data: memory, error: null } : { data: true, error: null })
    await (await harness.post()).text()
    expect(harness.state.captured[0].system).toContain('Prefiero conversar despacio')
    expect(harness.authClient.rpc).toHaveBeenCalledWith('get_profile_memory')
    expect(harness.service.rpc.mock.calls.map(call => call[0])).not.toContain('get_profile_memory')
    harness.authClient.rpc.mockImplementation(async (name: string) => name === 'get_profile_memory' ? { data: null, error: { code: 'PRIVATE' } } : { data: true, error: null })
    const next = await harness.post('Siguiente turno', 'turn-2')
    await next.text()
    expect(next.status).toBe(200)
    expect(harness.state.captured[1].system).not.toContain('Prefiero conversar despacio')
  })
  it('after dispatch failure cannot fail or duplicate the saved chat response', async () => {
    vi.stubEnv('FEATURE_PROGRESSIVE_PROFILE', 'on')
    const harness = await chatHarness()
    harness.enqueueProfileExtraction.mockRejectedValue(new Error('PRIVATE'))
    const response = await harness.post()
    await response.text()
    expect(response.status).toBe(200)
    await expect(harness.state.profileAfter[0]()).resolves.toBeUndefined()
    expect(harness.state.rows.filter(row => row.role === 'user')).toHaveLength(1)
  })
  it('omits optional memory if it would overflow an otherwise valid existing chat context', async () => {
    vi.stubEnv('FEATURE_PROGRESSIVE_PROFILE', 'on')
    const harness = await chatHarness()
    harness.state.rows.push({ id: 'previous-assistant', role: 'assistant', parts: [{ type: 'text', text: 'x'.repeat(78800) }] })
    harness.authClient.rpc.mockImplementation(async (name: string) => name === 'get_profile_memory' ? { data: memory, error: null } : { data: true, error: null })
    const response = await harness.post()
    await response.text()
    expect(response.status).toBe(200)
    expect(harness.state.captured[0].system).not.toContain('Prefiero conversar despacio')
  })
})

it('keeps ordinary hosted chat while denying profile reads/dispatch to a nonallowlisted Auth caller', async () => {
  vi.stubEnv('FEATURE_PROGRESSIVE_PROFILE', 'on'); vi.stubEnv('VERCEL', '1')
  vi.stubEnv('PROFILE_REVIEW_USER_IDS', id)
  const harness = await chatHarness()
  const response = await harness.post()
  await response.text()
  expect(response.status).toBe(200)
  expect(harness.authClient.rpc.mock.calls.flat()).not.toContain('get_profile_memory')
  expect(harness.state.profileAfter).toHaveLength(0)
  expect(harness.state.captured).toHaveLength(1)
})

it('passes verified hosted Auth identity to context and extraction, preserving wire IDs/token', async () => {
  vi.stubEnv('FEATURE_PROGRESSIVE_PROFILE', 'on'); vi.stubEnv('VERCEL', '1'); vi.stubEnv('PROFILE_REVIEW_USER_IDS', id)
  const harness = await chatHarness()
  harness.state.user = { id }; harness.state.session.user_id = id; harness.state.conversationOwner = id
  harness.authClient.rpc.mockImplementation(async (name: string) => ({ data: name === 'get_profile_memory' ? memory : true, error: null }))
  const response = await harness.post()
  await response.text()
  expect(response.status).toBe(200)
  expect(harness.state.captured[0].system).toContain('Prefiero conversar despacio')
  await harness.state.profileAfter[0]()
  expect(harness.enqueueProfileExtraction).toHaveBeenCalledWith(id, 1)
  const forged = await harness.post('Otro turno', 'turn-forged', { user_id: id, userId: id })
  expect(forged.status).toBe(400)
  expect(harness.state.profileAfter).toHaveLength(1)
})
it.each([undefined, '', '*', 'pablo@example.test'])('preserves base hosted chat with invalid review configuration %s', async list => {
  vi.stubEnv('FEATURE_PROGRESSIVE_PROFILE', 'on'); vi.stubEnv('VERCEL', '1'); vi.stubEnv('PROFILE_REVIEW_USER_IDS', list)
  const harness = await chatHarness()
  const response = await harness.post(); await response.text()
  expect(response.status).toBe(200)
  expect(harness.authClient.rpc.mock.calls.flat()).not.toContain('get_profile_memory')
  expect(harness.state.profileAfter).toHaveLength(0)
})
